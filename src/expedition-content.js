export function expeditionSites(m) {
  const authored = operationRoutes[m.chapter][m.order], anchors = authored[1].split('|');
  const chain = chains[m.kind];
  const stages = m.index === 0 ? 1 : m.chapter === 0 ? 2 : 3;
  const sites = [];
  for (let sector = 0; sector < anchors.length; sector++) for (let step = 0; step < stages; step++) {
    const last = sector === anchors.length - 1 && step === stages - 1;
    let task = chain[Math.min(step, 2)];
    if (m.kind === 'boss' && !last && task === 'guardian') task = 'battery';
    if (m.kind === 'boss' && last) task = 'guardian';
    const index = sites.length, column = index % 4, row = Math.floor(index / 4);
    // Winding local routes; different operations reverse the horizontal approach.
    const sign = m.order % 2 ? -1 : 1;
    const x = sign * ((row % 2 ? 3 - column : column) * 50 - 75);
    const z = -40 + row * 57;
    const decision = step === stages - 1 ? m.kind === 'salvage' ? 'salvage' : m.kind === 'relay' ? 'signal' : decisionTypes[(m.chapter + m.order + sector) % decisionTypes.length] : null;
    const instruction = tasks[task];
    sites.push({ id: `objective-${index}`, name: `${anchors[sector]}${stages > 1 ? ` · ${step+1}` : ''}`, label: String(index+1).padStart(2,'0'), x, z,
      task, waves: m.index === 0 ? 1 : instruction.waves, sector, last, decision: last ? null : decision,
      summary: instruction.summary, hint: task === 'battery' ? '장갑에 강한 관통포와 범위 공격을 조합하세요.' : task === 'escort' ? '작업선의 내구도는 다음 합류점까지 유지됩니다.' : '교전 후 정박해 재배치와 수리를 할 수 있습니다.',
      tier: Math.min(3,1+Math.floor(m.chapter/4)), danger: ['낮음','보통','높음'][Math.min(2,Math.floor(m.chapter/4))], reward: m.reward,
      enemies: [], narrative: authored[2],
    });
  }
  return sites;
}
